// Package bag provides bags (multisets) that count occurrences of each
// supported primitive type (Int8…Int64, Char, Float32, Float64). Each
// primitive has a hash bag (unordered, with immutable and synchronized
// wrappers) and a tree bag (sorted, base variant only). Go has no
// method-level generics, so the per-primitive sources are machine-generated
// rather than hand-maintained.
//
// For float types the two bag shapes treat values differently:
//
//   - The hash bag keys its backing map by the IEEE 754 bit pattern
//     (math.Float32bits / math.Float64bits, see the per-type *BagEntry), so
//     every NaN is a findable, countable key and +0.0 / -0.0 stay distinct —
//     unlike Go's native map equality on raw floats.
//   - The tree bag keeps entries sorted by the IEEE 754 total order (see
//     cmp_float.go) rather than the default partial <, so NaN and signed zeroes
//     order deterministically during binary search and in-order traversal.
//
// Production sources are regenerated by the in-repo code generator. Run:
//
//	go generate ./bag/...
//
// Test files are hand-maintained.
package bag

