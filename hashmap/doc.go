// Package hashmap provides open-addressing hash maps specialised for each
// supported key/value primitive pair (keys and values both range over
// Int8…Int64, Char, Float32, Float64), with immutable and synchronized
// wrappers. Go has no method-level generics, so the per-pair sources are
// machine-generated rather than hand-maintained. Keys are mixed with a
// golden-ratio hash; float keys are hashed and compared by their IEEE 754 bit
// pattern (so distinct NaNs and signed zeroes behave deterministically as map
// keys), and float values are likewise compared by bit pattern in
// ContainsValue / Equals. The package also provides bidirectional maps and two
// generic object-map shapes — Object<Value>[K comparable] (object keys
// hashed via the shared hashComparable helper, prim values) and
// <Key>Object[V any] (prim keys, generic values) — each with an
// immutable wrapper.
//
// Production sources are regenerated by the in-repo code generator. Run:
//
//	go generate ./hashmap/...
//
// Test files are hand-maintained.
