package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// Family describes one code-generated collection family: the structural facts
// that the generator and the documentation derive from. It is the single
// declarative source that replaces knowledge previously scattered across the
// per-generator functions (todo/fable-golang/14 §1b — the family×variant
// manifest). Today it drives the generated family matrix (FAMILY_MATRIX.md);
// the generation loops and the collection/ interface files are ported onto it
// incrementally, each step keeping generated output byte-identical.
//
// Scope: the 13 code-generated families only. Hand-written collections (bitset)
// and the algorithmic/probabilistic packages (roaring, bloom, hyperloglog, …)
// are not generated, so they are documented in README.md, not here.
type Family struct {
	Name         string // display name (ArrayList, HashMap, …)
	Package      string // module-relative package directory (arraylist, hashmap, …)
	Storage      string // backing structure, as a human phrase
	Order        string // iteration / access order
	Elements     string // element or key–value type coverage
	Immutable    bool   // has an Immutable… variant for its primary backing
	Synchronized bool   // has a Synchronized… variant for its primary backing
	Extra        string // family-specific extra variants, or "" for none
}

// Families is the manifest: every code-generated collection family. Every field
// is a fact verifiable against the committed sources — the generated matrix is
// the cross-check. (A few adjuncts noted in Extra, e.g. the treeset/treemap
// navigable-range views, are hand-written rather than generated.)
var Families = []Family{
	{"ArrayList", "arraylist", "`[]T` slice", "insertion", "7 primitives", true, true, ""},
	{"ArrayStack", "stack", "`[]T` slice", "LIFO", "7 primitives", true, true, ""},
	{"ArrayDeque", "deque", "ring buffer over `[]T`", "double-ended (insertion)", "7 primitives", false, true, ""},
	{"PriorityQueue", "priorityqueue", "binary min-heap over `[]T`", "min-first (heap)", "7 primitives", false, true, ""},
	{"Interval", "interval", "computed (from/to/step)", "sequence in step direction (asc/desc)", "4 signed ints (int8/16/32/64)", false, false, "lazy; float32/64 emit \"not applicable\" stubs, no char"},
	{"HashSet", "hashset", "open-addressing hash", "unordered", "8 (7 primitives + bool)", true, true, ""},
	{"TreeSet", "treeset", "red-black tree", "sorted (natural order)", "7 primitives", false, false, "navigable range views (hand-written, int32)"},
	{"HashMap", "hashmap", "open-addressing hash", "unordered", "49 primitive pairs (7×7)", true, true, "bimap, object-key, object-value"},
	{"SentinelHashMap", "sentinelhashmap", "open-addressing hash (sentinel key)", "unordered", "49 pairs (7×7)", false, false, ""},
	{"TreeMap", "treemap", "red-black tree", "sorted (natural order)", "49 pairs (7×7)", false, false, "navigable range views (hand-written, int32)"},
	{"Multimap", "multimap", "hash map of per-key collections", "unordered keys", "49 pairs (7×7)", false, false, "list- & set-valued"},
	{"Bag", "bag", "hash (`map`) or sorted slice (binary search)", "unordered (hash) / sorted (tree)", "7 primitives", true, true, "tree-backed variant (base only)"},
	{"Pair", "tuple", "value struct (2-tuple)", "n/a (fixed arity)", "49 pairs (7×7)", false, false, "object-key, object-value"},
}

// tick renders a boolean manifest cell for the markdown matrix.
func tick(b bool) string {
	if b {
		return "✓"
	}
	return "—"
}

// dashIfEmpty renders an optional string manifest cell, showing an em dash when
// the value is empty so every column stays populated.
func dashIfEmpty(s string) string {
	if s == "" {
		return "—"
	}
	return s
}

// renderFamilyMatrix builds the Markdown body of FAMILY_MATRIX.md from Families.
// It carries the same "Code generated … DO NOT EDIT" banner (as an HTML comment,
// since Markdown has no line comments) that the codegen drift gate relies on for
// the .go sources; here the gate catches drift through git diff after
// regeneration rather than by pre-deleting the file.
func renderFamilyMatrix() string {
	var b strings.Builder
	b.WriteString("<!-- Code generated by internal/codegen; DO NOT EDIT. -->\n")
	b.WriteString("<!-- Edit internal/codegen/manifest.go and run `go generate ./...`. -->\n\n")
	b.WriteString("# Code-generated collection families\n\n")
	b.WriteString("The families below are generated per primitive from `internal/codegen`.\n")
	b.WriteString("`Pair` is a fixed-arity value type rather than a collection; it is listed\n")
	b.WriteString("because it shares the generator. Hand-written collections (`bitset`) and the\n")
	b.WriteString("algorithmic/probabilistic packages are documented in the top-level `README.md`.\n\n")
	b.WriteString("| Family | Package | Storage | Order | Element / key–value types | Immutable | Synchronized | Other variants |\n")
	b.WriteString("|---|---|---|---|---|---|---|---|\n")
	for _, f := range Families {
		fmt.Fprintf(&b, "| %s | `%s` | %s | %s | %s | %s | %s | %s |\n",
			f.Name, f.Package, f.Storage, f.Order, f.Elements,
			tick(f.Immutable), tick(f.Synchronized), dashIfEmpty(f.Extra))
	}
	return b.String()
}

// genFamilyMatrix writes FAMILY_MATRIX.md into the current working directory
// (collection/, via its go:generate directive) from the manifest.
func genFamilyMatrix() error {
	cwd, err := os.Getwd()
	if err != nil {
		return err
	}
	out := filepath.Join(cwd, "FAMILY_MATRIX.md")
	return os.WriteFile(out, []byte(renderFamilyMatrix()), 0o644)
}
