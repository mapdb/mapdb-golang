// Package multimap provides multimaps — maps from a single key to a collection
// of values — specialised for each supported key/value primitive pair (keys and
// values both range over Int8…Int64, Char, Float32, Float64). Two flavours are
// provided per pair: a list multimap (*_list_multimap.go), which appends and
// keeps duplicate values per key, and a set multimap (*_set_multimap.go), which
// dedups values per key. Go has no method-level generics, so these per-pair
// sources are machine-generated rather than hand-maintained.
//
// The backing store is a Go builtin map. For float keys this is structurally
// different: because Go builtin maps cannot safely key on floats (NaN is
// unreachable and ±0 collapse), float-keyed multimaps key the data map on the
// IEEE 754 bit pattern and carry a side map to recover the original float key
// during iteration. Set multimaps dedup float values by bit pattern, and both
// flavours compare float values by bit pattern in Equals.
//
// The generic Multimap[K comparable, V any] in multimap.go is hand-written and
// is NOT produced by the generator.
//
// The per-pair production sources are regenerated by the in-repo code generator.
// Run:
//
//	go generate ./multimap/...
//
// Test files are hand-maintained.
package multimap

