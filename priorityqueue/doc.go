// Package priorityqueue provides binary min-heap priority queues specialised
// for each supported primitive type (Int8…Int64, Char, Float32, Float64), each
// with a synchronized wrapper. Go has no method-level generics, so the
// per-primitive sources are machine-generated rather than hand-maintained. For
// float types, the heap ordering uses the IEEE 754 total order (see
// cmp_float.go) rather than the default partial <, which sorts deterministically
// (-NaN < -Inf < negatives < -0.0 < +0.0 < positives < +Inf < +NaN): a queued
// positive NaN sinks to the bottom of the min-heap and drains last, while a
// negative NaN drains first. Contains compares float bit patterns
// (math.FloatNNbits) so a queued NaN can still be found.
//
// Bulk import (data pump): the family-wide data-pump feature needs no new code
// here. Int<T>Of already performs an O(n) Floyd heapify in a single pass, so it
// IS the heap's bulk-load path; there is deliberately no separate FromSorted /
// BulkLoad constructor.
//
// Production sources are regenerated by the in-repo code generator. Run:
//
//	go generate ./priorityqueue/...
//
// Test files are hand-maintained.
