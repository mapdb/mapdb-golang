// Package sentinelhashmap provides open-addressing hash maps specialised for
// each supported key/value primitive pair (keys and values both range over
// Int8…Int64, Char, Float32, Float64). Go has no method-level generics, so the
// per-pair sources are machine-generated rather than hand-maintained.
//
// Unlike the hashmap package, slot state is not tracked with a parallel
// occupied []bool array. Instead two key values are reserved as in-table
// markers — 0 (empty) and 1 (removed). Because 0 and 1 are also valid user
// keys, they are stored in dedicated struct fields (zeroKey*/oneKey*) and every
// operation special-cases them. For float keys, +0.0 collides with the empty
// marker, so -0.0 is additionally routed to its own field keyed on the IEEE-754
// bit pattern; float key equality at the probe sites uses bit-pattern equality
// rather than ==. Float values likewise use bit-pattern equality in
// ContainsValue.
//
// Production sources are regenerated by the in-repo code generator. Run:
//
//	go generate ./sentinelhashmap/...
//
// Test files are hand-maintained.
package sentinelhashmap

