// Package treeset provides sorted sets backed by a red-black tree, specialised
// for each supported primitive type (Int8…Int64, Char, Float32, Float64). Go
// has no method-level generics, so the per-primitive sources are
// machine-generated rather than hand-maintained. For float types, insertion
// and in-order traversal use the IEEE 754 total order (see cmp_float.go) rather
// than the default partial <, so NaN and signed zeroes sort deterministically;
// the Floor/Ceiling/RangeValues bound and exact-match checks use raw == / < / >=
// (matching the hand-written originals), so their NaN / signed-zero edge
// behaviour follows IEEE comparison, not the total order.
//
// Production sources are regenerated by the in-repo code generator. Run:
//
//	go generate ./treeset/...
//
// Test files are hand-maintained.
