// Package treeset provides sorted sets backed by a red-black tree, specialised
// for each supported primitive type (Int8…Int64, Char, Float32, Float64). Go
// has no method-level generics, so the per-primitive sources are
// machine-generated rather than hand-maintained. For float types, insertion
// and in-order traversal use the IEEE 754 total order (see cmp_float.go) rather
// than the default partial <, so NaN and signed zeroes sort deterministically.
// The Floor/Ceiling exact-match short-circuits and the RangeValues bound checks
// route through the same cmpFloat32/64, so float navigation is a total order
// throughout (NaN sorts to the top, ±0 are distinguished); integer and char
// element types keep raw == / < / >=.
//
// Production sources are regenerated by the in-repo code generator. Run:
//
//	go generate ./treeset/...
//
// Test files are hand-maintained. The NavigableSet Range surface
// (SubSet/RangeElements/RemoveRange/... consuming rangev.Int32Range) is
// int32-only in v1, so it lives in the hand-maintained
// int32_navigable_range.go rather than the uniform generated sources; the
// generator does not touch that file.
